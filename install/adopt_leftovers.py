"""Adopt the leftovers of an earlier deployment in the same project (destroy -> redeploy), before Terraform runs.

A destroyed log bucket stays DELETE_REQUESTED for 7 days and keeps its name reserved, and the destroy schedules the
destruction of its CMEK key versions (24 h). Re-creating a bucket with the same name then fails. For every fixed-name
log bucket this configuration manages:
  1. CMEK key: restore + re-enable DESTROY_SCHEDULED versions of the bucket's key and give the Logging service agent
     its key role back (a DESTROYED key version = logs unrecoverable: stop with the options);
  2. undelete a DELETE_REQUESTED bucket (logs kept);
  3. existing bucket not in the Terraform state: write an import block to terraform/zz-adopt-imports.tf (GENERATED,
     never committed); the next full apply imports + updates it in one plan and install.sh then removes the file.
     (CLI `terraform import` evaluates the whole configuration and fails on unknown for_each keys after a destroy.)
     A tainted bucket in the state is untainted (state-only operation).
Order: all key repairs, then all undeletes, then the state step. Nothing exists (fresh project) = no-op.

Usage: install/adopt_leftovers.py --project P --region R --tf-dir terraform --gateway-image IMG
         --bucket <bucket-id>=<terraform address> [--bucket ...]
Exit: 0 = done / nothing to do, 3 = stop (key destroyed; message printed), 1 = a command failed.
"""
from __future__ import annotations

import argparse
import dataclasses
import json
import os
import re
import subprocess
import sys
import time
from typing import Callable

os.environ["CLOUDSDK_CORE_DISABLE_PROMPTS"] = "1"
Runner = Callable[[list[str]], "tuple[int, str, str]"]
KEY_RE = re.compile(r"^projects/([^/]+)/locations/([^/]+)/keyRings/([^/]+)/cryptoKeys/([^/]+)$")
KMS_ROLE = "roles/cloudkms.cryptoKeyEncrypterDecrypter"
IMPORTS_FILE = "zz-adopt-imports.tf"
TEMPLATE_FILE = "zz-template-suffix.auto.tfvars"
TEMPLATE_ADDRESS = "module.mtls[0].google_privateca_certificate_template.device"
TEMPLATE_HEADER = ("# GENERATED by install.sh: CAS never reuses a certificate template id, and an earlier deployment in this project\n"
                   "# used the default one. Keep this file (every later run needs the same suffix); never commit. --destroy removes it.\n")


def head(text: str, lines: int = 15, chars: int = 1500) -> str:
    """The FIRST lines of a tool's error output (the cause), not the tail."""
    keep = "\n".join(line.rstrip() for line in text.strip().splitlines() if line.strip())
    return "\n".join(keep.splitlines()[:lines])[:chars]


class Stop(Exception):
    """Unrecoverable leftover: the operator has to choose (message is customer-facing)."""


class Failed(Exception):
    """A command failed."""


def run(cmd: list[str]) -> tuple[int, str, str]:
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=600)
        return p.returncode, p.stdout, p.stderr
    except (OSError, subprocess.TimeoutExpired) as e:
        return 1, "", str(e)


def log(msg: str) -> None:
    print(f"\033[1;34m[adopt]\033[0m {msg}", flush=True)


@dataclasses.dataclass
class Bucket:
    bucket_id: str
    address: str
    exists: bool = False
    state: str = ""            # ACTIVE | DELETE_REQUESTED
    kms_key: str = ""          # projects/.../cryptoKeys/<k>
    kms_version: str = ""      # .../cryptoKeyVersions/<n> in use (may be empty)
    service_account: str = ""  # Logging service agent of the bucket's CMEK settings
    in_state: bool = False
    tainted: bool = False

    @property
    def undelete(self) -> bool:
        return self.exists and self.state == "DELETE_REQUESTED"

    @property
    def import_(self) -> bool:
        return self.exists and not self.in_state

    @property
    def untaint(self) -> bool:
        return self.exists and self.in_state and self.tainted

    @property
    def adopt(self) -> bool:
        return self.undelete or self.import_ or self.untaint


def state_names(show_json: str) -> dict[str, str]:
    """terraform show -json -> {address: values.name} (where the resource has a name)."""
    try:
        doc = json.loads(show_json or "{}")
    except ValueError:
        return {}
    out: dict[str, str] = {}

    def walk(mod: dict) -> None:
        for r in mod.get("resources", []) or []:
            if isinstance(r.get("values"), dict) and r["values"].get("name"):
                out[r["address"]] = str(r["values"]["name"])
        for c in mod.get("child_modules", []) or []:
            walk(c)
    walk(doc.get("values", {}).get("root_module", {}) or {})
    return out


def state_resources(show_json: str) -> dict[str, bool]:
    """terraform show -json -> {address: tainted} for every managed resource in the state."""
    try:
        doc = json.loads(show_json or "{}")
    except ValueError:
        return {}
    out: dict[str, bool] = {}

    def walk(mod: dict) -> None:
        for r in mod.get("resources", []) or []:
            if r.get("mode", "managed") == "managed":
                out[r["address"]] = bool(r.get("tainted", False))
        for c in mod.get("child_modules", []) or []:
            walk(c)
    walk(doc.get("values", {}).get("root_module", {}) or {})
    return out


class Adopter:
    def __init__(self, project: str, region: str, tf_dir: str, gateway_image: str, runner: Runner = run,
                 sleep: Callable[[float], None] = time.sleep, prefix: str = "agy", template_suffix: str = "",
                 new_suffix: Callable[[], str] = lambda: os.urandom(3).hex()) -> None:
        self.project, self.region, self.tf_dir, self.image = project, region, tf_dir, gateway_image
        self.prefix, self.template_suffix_set, self.new_suffix = prefix, template_suffix, new_suffix
        self.run, self.sleep = runner, sleep
        self.done: list[str] = []

    # ------------------------------------------------------------------ helpers
    def must(self, cmd: list[str], what: str) -> str:
        rc, out, err = self.run(cmd)
        if rc != 0:
            raise Failed(f"{what} failed:\n{head(err or out)}\n  command: {' '.join(cmd)}")
        self.done.append(" ".join(cmd))
        return out

    def tf(self, *args: str) -> list[str]:
        return ["terraform", f"-chdir={self.tf_dir}", *args]

    def describe(self, b: Bucket) -> None:
        rc, out, err = self.run(["gcloud", "logging", "buckets", "describe", b.bucket_id, "--location", self.region,
                                 "--project", self.project, "--format=json"])
        if rc != 0:
            if re.search(r"NOT_FOUND|not found|does not exist", err or out, re.I):
                return
            raise Failed(f"cannot read log bucket {b.bucket_id}:\n{head(err or out)}")
        d = json.loads(out or "{}")
        cmek = d.get("cmekSettings", {}) or {}
        b.exists, b.state = True, d.get("lifecycleState", "ACTIVE")
        b.kms_key, b.kms_version = cmek.get("kmsKeyName", ""), cmek.get("kmsKeyVersionName", "")
        b.service_account = cmek.get("serviceAccountId", "")

    # ------------------------------------------------------------------ key repair (before any undelete)
    def repair_key(self, key: str, used_version: str, buckets: list[str], service_account: str) -> None:
        m = KEY_RE.match(key)
        if not m:
            raise Failed(f"unexpected KMS key name {key!r}")
        kproj, loc, ring, name = m.groups()
        sel = ["--key", name, "--keyring", ring, "--location", loc, "--project", kproj]
        out = self.must(["gcloud", "kms", "keys", "versions", "list", *sel, "--format=json"], f"listing versions of {key}")
        versions = {v["name"]: v.get("state", "") for v in json.loads(out or "[]")}
        used = used_version or next((n for n, s in versions.items() if s in ("ENABLED", "DESTROY_SCHEDULED", "DISABLED")), "")
        if used and versions.get(used) in ("DESTROYED", "DESTROY_REQUESTED"):
            raise Stop(
                f"log bucket(s) {', '.join(buckets)} of an earlier deployment are encrypted with {used}, which is already "
                "DESTROYED: their logs can't be recovered and the bucket name(s) stay reserved until the 7-day pending "
                "deletion ends.\n  Options: (a) deploy into a new project (cleanest); (b) use other names: set "
                "log_bucket_id (security bucket) and/or name_prefix (audit / SIEM buckets) in terraform/custom.auto.tfvars; "
                "(c) wait until the pending deletion has ended, then re-run.")
        for v, st in sorted(versions.items()):
            n = v.rsplit("/", 1)[-1]
            if st == "DESTROY_SCHEDULED":
                log(f"restoring CMEK key version {n} of {ring}/{name} (scheduled for destruction by the earlier destroy)")
                self.must(["gcloud", "kms", "keys", "versions", "restore", n, *sel, "--quiet"], f"restoring {v}")
                self.must(["gcloud", "kms", "keys", "versions", "enable", n, *sel, "--quiet"], f"enabling {v}")
            elif st == "DISABLED" and v == used:
                log(f"re-enabling CMEK key version {n} of {ring}/{name}")
                self.must(["gcloud", "kms", "keys", "versions", "enable", n, *sel, "--quiet"], f"enabling {v}")
        if service_account:   # the destroy removed the Logging agent's role on the old key: needed to read the old logs
            self.must(["gcloud", "kms", "keys", "add-iam-policy-binding", name, "--keyring", ring, "--location", loc,
                       "--project", kproj, "--member", f"serviceAccount:{service_account}", "--role", KMS_ROLE, "--quiet"],
                      f"granting the Logging service agent {KMS_ROLE} on {key}")

    def write_imports(self, buckets: list[Bucket]) -> None:
        """Import blocks (Terraform >= 1.5) for existing buckets that are not in the state; no block = no file."""
        path = os.path.join(self.tf_dir, IMPORTS_FILE)
        if not buckets:
            if os.path.exists(path):
                os.remove(path)
            return
        blocks = [f'import {{\n  to = {b.address}\n  id = "projects/{self.project}/locations/{self.region}/buckets/'
                  f'{b.bucket_id}"\n}}\n' for b in buckets]
        with open(path, "w", encoding="utf-8") as f:
            f.write("# GENERATED by install/adopt_leftovers.py (destroy -> redeploy in the same project): log buckets of an\n"
                    "# earlier deployment to adopt. install.sh removes this file after the next successful apply. Never commit.\n"
                    + "\n".join(blocks))
        self.done.append(f"wrote {path}")

    def write_template_suffix(self, sfx: str) -> None:
        with open(os.path.join(self.tf_dir, TEMPLATE_FILE), "w", encoding="utf-8") as f:
            f.write(TEMPLATE_HEADER + f'cas_template_suffix = "{sfx}"\n')

    def template_suffix(self, show_json: str, in_state: dict[str, bool], leftovers: bool) -> None:
        """CAS certificate template ids are never reusable after deletion (the stack's template name is fixed).
        Configured suffix -> keep. Template in the state with a suffix (e.g. new checkout) -> persist that suffix.
        Redeploy (leftovers adopted) and no template in the state -> new suffix up front. Otherwise install.sh's retry
        switches the suffix when CAS answers "Previously used CertificateTemplate ids may not be reused"."""
        if self.template_suffix_set:
            return
        base = f"{self.prefix}-device-client"
        name = state_names(show_json).get(TEMPLATE_ADDRESS, "")
        if name.rsplit("/", 1)[-1].startswith(base + "-"):
            sfx = name.rsplit("/", 1)[-1][len(base) + 1:]
            log(f"certificate template {base}-{sfx} is in the state: keeping its suffix ({TEMPLATE_FILE})")
            self.write_template_suffix(sfx)
        elif TEMPLATE_ADDRESS not in in_state and leftovers:
            sfx = self.new_suffix()
            log(f"certificate template id {base} was used by an earlier deployment (CAS never reuses ids) - "
                f"using {base}-{sfx}")
            self.write_template_suffix(sfx)

    # ------------------------------------------------------------------ main flow
    def adopt(self, buckets: list[Bucket]) -> int:
        show = self.must(self.tf("show", "-json", "-no-color"), "reading the Terraform state")
        states = state_resources(show)
        for b in buckets:
            self.describe(b)
            b.in_state, b.tainted = b.address in states, states.get(b.address, False)
        todo = [b for b in buckets if b.adopt]
        self.template_suffix(show, states, bool(todo))
        if not todo:
            self.write_imports([])   # remove a stale file (its buckets are managed now)
            log("no leftovers of an earlier deployment (log buckets)")
            return 0
        # 1. keys of buckets that come back (dedupe per key)
        keys: dict[str, list[Bucket]] = {}
        for b in todo:
            if b.kms_key and (b.undelete or b.import_):
                keys.setdefault(b.kms_key, []).append(b)
        for key, bs in keys.items():
            self.repair_key(key, next((b.kms_version for b in bs if b.kms_version), ""), [b.bucket_id for b in bs],
                            next((b.service_account for b in bs if b.service_account), ""))
        # 2. undelete (logs kept)
        for b in todo:
            if b.undelete:
                log(f"undeleting log bucket {b.bucket_id} (pending deletion since the earlier destroy; logs kept)")
                self.must(["gcloud", "logging", "buckets", "undelete", b.bucket_id, "--location", self.region,
                           "--project", self.project, "--quiet"], f"undeleting {b.bucket_id}")
                for _ in range(12):   # becomes ACTIVE within seconds
                    self.describe(b)
                    if b.state == "ACTIVE":
                        break
                    self.sleep(5)
        # 3. Terraform state: import blocks for the next apply; untaint (state only, no config evaluation)
        imports = [b for b in todo if b.import_]
        for b in imports:
            log(f"log bucket {b.bucket_id} will be imported by the next Terraform apply ({b.address}; "
                f"{os.path.join(self.tf_dir, IMPORTS_FILE)})")
        self.write_imports(imports)
        for b in todo:
            if b.untaint:
                log(f"untainting {b.address} (the bucket exists; replacing it would fail on the reserved name)")
                self.must(self.tf("untaint", "-lock-timeout=120s", b.address), f"untainting {b.address}")
        log(f"adopted {len(todo)} log bucket(s) of an earlier deployment: {', '.join(b.bucket_id for b in todo)}")
        return 0


def main(argv: list[str] | None = None, runner: Runner = run) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--project", required=True)
    ap.add_argument("--region", required=True)
    ap.add_argument("--tf-dir", required=True)
    ap.add_argument("--gateway-image", default="")
    ap.add_argument("--bucket", action="append", default=[], help="<bucket-id>=<terraform address>")
    ap.add_argument("--name-prefix", default="agy")
    ap.add_argument("--template-suffix", default="", help="cas_template_suffix in effect (empty = default id)")
    a = ap.parse_args(argv)
    buckets = []
    for spec in a.bucket:
        bid, _, addr = spec.partition("=")
        if not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}", bid) or not addr:
            print(f"ERROR: --bucket {spec!r} must be <bucket-id>=<terraform address>", file=sys.stderr)
            return 1
        buckets.append(Bucket(bid, addr))
    try:
        return Adopter(a.project, a.region, a.tf_dir, a.gateway_image, runner, prefix=a.name_prefix,
                       template_suffix=a.template_suffix).adopt(buckets)
    except Stop as e:
        print(f"\033[1;31m[adopt] STOP:\033[0m {e}", file=sys.stderr)
        return 3
    except Failed as e:
        print(f"\033[1;31m[adopt] ERROR:\033[0m {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
