# Bootstrap the remote Terraform state: CMEK key (outside the main stack) + GCS bucket + backend.hcl.
# Idempotent. Usage: install/state-bootstrap.sh <project-id> <region>
set -euo pipefail
export CLOUDSDK_CORE_DISABLE_PROMPTS=1   # a hidden "enable API and retry? (y/N)" prompt (output -> /dev/null) would hang
PROJECT="${1:?project id}"; REGION="${2:?region}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BUCKET="${PROJECT}-agy-tfstate"
RING="agy-tfstate-ring"; KEY="agy-tfstate-key"
COST_CENTER="$(printf %s "${COST_CENTER:-security}" | tr -cd "a-z0-9_-")"   # label value from install.conf
KEY_ID="projects/${PROJECT}/locations/${REGION}/keyRings/${RING}/cryptoKeys/${KEY}"
log() { printf '\033[1;34m[state]\033[0m %s\n' "$*"; }

log "checking billing (Cloud Billing API is free to enable)"
gcloud services enable cloudbilling.googleapis.com --project "$PROJECT" --quiet >/dev/null 2>&1 || true
BILLING="$(curl -fsS -H "Authorization: Bearer $(gcloud auth print-access-token)" -H "X-Goog-User-Project: ${PROJECT}" \
  "https://cloudbilling.googleapis.com/v1/projects/${PROJECT}/billingInfo" 2>/dev/null || true)"
if grep -q '"billingEnabled": *true' <<<"$BILLING"; then
  log "billing: linked"
elif [[ -n "$BILLING" ]]; then
  echo "ERROR: project ${PROJECT} has no active billing account - link one (Billing > Account management) and re-run" >&2; exit 3
else
  log "billing: not readable with your permissions - continuing (API enablement fails fast without billing)"
fi

log "enabling bootstrap APIs (serviceusage, cloudresourcemanager, storage, cloudkms)"
gcloud services enable serviceusage.googleapis.com cloudresourcemanager.googleapis.com \
  storage.googleapis.com cloudkms.googleapis.com iam.googleapis.com --project "$PROJECT" --quiet
# a freshly enabled API can answer SERVICE_DISABLED for a few minutes (seen on a clean project): wait for KMS
for i in $(seq 1 30); do
  gcloud kms locations list --project "$PROJECT" --limit 1 >/dev/null 2>&1 && break
  [[ $i -eq 30 ]] && { echo "ERROR: Cloud KMS API still not ready on ${PROJECT} after 5 minutes - re-run" >&2; exit 4; }
  log "Cloud KMS API not ready yet (new API enablement propagating) - retry $i/30"; sleep 10
done

log "CMEK key ${RING}/${KEY} (${REGION}) - separate from the POC stack so destroy can never remove it"
gcloud kms keyrings describe "$RING" --location "$REGION" --project "$PROJECT" >/dev/null 2>&1 \
  || gcloud kms keyrings create "$RING" --location "$REGION" --project "$PROJECT"
gcloud kms keys describe "$KEY" --keyring "$RING" --location "$REGION" --project "$PROJECT" >/dev/null 2>&1 \
  || gcloud kms keys create "$KEY" --keyring "$RING" --location "$REGION" --project "$PROJECT" \
       --purpose encryption --rotation-period 90d --next-rotation-time "$(date -u -v+90d +%Y-%m-%dT%H:%M:%SZ 2>/dev/null || date -u -d '+90 days' +%Y-%m-%dT%H:%M:%SZ)" \
       --labels environment=poc,data_classification=confidential,cost_center=${COST_CENTER:-security},workload=antigravity-controls-poc

log "granting the Cloud Storage service agent use of the key"
# --authorize-cmek provisions the Storage service agent if needed (clean projects) and grants it the key
for i in 1 2 3 4 5; do
  gcloud storage service-agent --project "$PROJECT" --authorize-cmek "$KEY_ID" >/dev/null && break
  log "service agent not ready yet - retry $i"; sleep 10
done

log "state bucket gs://${BUCKET} (versioned, UBLA, public access prevention, CMEK, soft delete 7d)"
if ! gcloud storage buckets describe "gs://${BUCKET}" --project "$PROJECT" >/dev/null 2>&1; then
  gcloud storage buckets create "gs://${BUCKET}" --project "$PROJECT" --location "$REGION" \
    --uniform-bucket-level-access --public-access-prevention --default-encryption-key "$KEY_ID" \
    --soft-delete-duration 7d
fi
gcloud storage buckets update "gs://${BUCKET}" --versioning --default-encryption-key "$KEY_ID" \
  --update-labels environment=poc,data_classification=confidential,cost_center=${COST_CENTER:-security},workload=antigravity-controls-poc,purpose=terraform-state >/dev/null

cat > "$ROOT/terraform/backend.hcl" <<EOF
# generated by install/state-bootstrap.sh - git-ignored
bucket = "${BUCKET}"
prefix = "agy-poc/state"
EOF
log "backend.hcl written -> bucket=${BUCKET} prefix=agy-poc/state"
